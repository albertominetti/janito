#!/usr/bin/env bash
#
# install-janito-dev.sh - install this repo as the `janito-dev` command.
#
# Usage: ./scripts/install-janito-dev.sh
#
# Picks the first available tool: uv > conda > pip.
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENV_DIR="$REPO_ROOT/.venv-dev"
VENV_PYTHON="$VENV_DIR/bin/python"
BIN_FILE="$HOME/.local/bin/janito-dev"

if [ ! -x "$VENV_PYTHON" ]; then
    if command -v uv >/dev/null 2>&1; then
        echo "Using uv"
        uv venv "$VENV_DIR"
    elif command -v conda >/dev/null 2>&1; then
        echo "Using conda"
        conda create --prefix "$VENV_DIR" python=3.11 -y
    elif command -v python3 >/dev/null 2>&1; then
        echo "Using pip"
        python3 -m venv "$VENV_DIR"
    else
        echo "install-janito-dev.sh: error: need uv, conda or python3 on PATH" >&2
        exit 1
    fi
fi

if command -v uv >/dev/null 2>&1; then
    uv pip install --python "$VENV_PYTHON" -e "$REPO_ROOT"
else
    "$VENV_PYTHON" -m pip install -e "$REPO_ROOT"
fi

mkdir -p "$(dirname "$BIN_FILE")"
printf '#!/usr/bin/env sh\n# Auto-generated by scripts/install-janito-dev.sh - do not edit.\nexec "%s" -m janito "$@"\n' "$VENV_PYTHON" > "$BIN_FILE"
chmod +x "$BIN_FILE"

echo "Done: $BIN_FILE"
"$VENV_PYTHON" -m janito --version
